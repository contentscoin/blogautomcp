/** 은/는 조사. 괄호·기호로 끝나면 그 앞 글자를 본다. 한글·숫자 외에는 "은"으로 둔다. */
export function topicParticle(word: string): "은" | "는" {
  const core = word.replace(/[^\p{L}\p{N}]+$/u, "");
  const last = core.slice(-1);
  if (!last) return "은";
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) return (code - 0xac00) % 28 === 0 ? "는" : "은";
  if (/\d/u.test(last)) return /[2459]/u.test(last) ? "는" : "은";
  return "은";
}

export function classifyHighlight(name: string): HighlightKind {
  for (const [kind, pattern] of KIND_PATTERNS) {
    if (pattern.test(name)) return kind;
  }
  return "generic";
}

