/** 이름(방문지·목적지)에 맞는 배경 지식 한 줄. `used` 에 있는 키는 건너뛰어 같은 문장을 두 번 쓰지 않는다. */
export function findDestinationKnowledge(name: string, used: Set<string> = new Set()): { key: string; line: string } | null {
  for (const entry of DESTINATION_KNOWLEDGE) {
    if (used.has(entry.key)) continue;
    if (entry.pattern.test(name)) return { key: entry.key, line: entry.line };
  }
  return null;
}

