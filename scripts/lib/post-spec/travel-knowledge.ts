/** 유형별로 준비된 서로 다른 문장 세트 수. */
export function highlightCopyVariantCount(kind: HighlightKind): number {
  return kind === "generic" ? 0 : COPY[kind].length;
}

/** generic 변형이 다른 코스 포인트와 겹치지 않는지 판단할 때 쓴다. */
export function usesGenericCopy(kind: HighlightKind, variant: number): boolean {
  return kind === "generic" || variant >= highlightCopyVariantCount(kind);
}

/** 방문지 유형과 변형 번호에 맞는 코스 포인트 문장 4줄. 같은 유형이 변형 수보다 많으면 generic 변형으로 넘어간다. */
export function buildHighlightCourseLines(input: HighlightCopyInput): string[] {
  const kind = classifyHighlight(input.highlight);
  const place = input.highlight.trim() || "주요 방문지";
  const destination = input.destination.trim() || "이 지역";
  if (!usesGenericCopy(kind, input.variant)) return COPY[kind][input.variant](place, destination);
  const generic = COPY.generic;
  return generic[(input.genericVariant ?? 0) % generic.length](place, destination);
}
